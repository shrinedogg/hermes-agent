def apply(conn) -> None:
    """Create ``conn``'s schema (its search_path must point at it): idempotent, one transaction, committed.
    One statement per execute (the driver rejects multi-statement batches); the trigger functions run before
    the triggers that name them; the bundled ``DROP TRIGGER`` + ``CREATE TRIGGER`` entries run as their two
    statements."""
    statements = [s for s in STATEMENTS if s.startswith("CREATE OR REPLACE FUNCTION")]
    statements += [s for s in STATEMENTS if not s.startswith("CREATE OR REPLACE FUNCTION")]
    for statement in statements:
        if statement.startswith("DROP TRIGGER") and "CREATE TRIGGER" in statement:
            split = statement.index("CREATE TRIGGER")
            conn.execute(statement[:split].strip())
            conn.execute(statement[split:].strip())
        else:
            conn.execute(statement)
    if not conn.execute("SELECT 1 FROM schema_version LIMIT 1").fetchone():
        conn.execute("INSERT INTO schema_version(version) VALUES (%s)", (SCHEMA_VERSION,))
    conn.commit()
